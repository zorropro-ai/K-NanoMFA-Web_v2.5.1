'use strict';
const assert=require('assert');
const B=require('./benchmark_validation.js');
const cov=B.coverage();
assert(cov.studies>=10,`expected >=10 independent studies, got ${cov.studies}`);
assert(cov.material_count>=9,`expected >=9 material classes, got ${cov.material_count}`);
assert(B.forMaterial('CNT').length>=8,'CNT should have multiple independent comparison records');
assert(B.forMaterial('nano-TiO2').length>=6,'nano-TiO2 should have multiple comparison records');
assert(B.forMaterial('AgNP').length>=5,'AgNP should have multiple comparison records');
assert(B.forMaterial('Nanoclay').length===0,'Nanoclay must not receive a chemically unrelated proxy benchmark');
const a=B.applicability(B.forMaterial('CNT').find(x=>x.id==='bornhoft2016-cnt-soil-2025'),{country_code:'DE',year:2025});
assert(a.score>=80,`same-region/same-year CNT benchmark should be high applicability, got ${a.score}`);
const inRange=B.concordance(0.0006,B.forMaterial('CNT').find(x=>x.id==='mueller2008-cnt-water'));
assert.strictEqual(inRange.score,100);
const far=B.concordance(0.6,B.forMaterial('CNT').find(x=>x.id==='mueller2008-cnt-water'));
assert(far.score<50,'three-order mismatch should have limited/low concordance');
const rows=B.forMaterial('CNT').map(b=>({...b,app:B.applicability(b,{country_code:'KR',year:2025}),concordance:B.concordance(Number.isFinite(b.target)?b.target:(b.min+b.max)/2,b)}));
const sum=B.summary(rows);
assert(Number.isFinite(sum.study_weighted_mean_applicability));
assert(Number.isFinite(sum.applicability_weighted_concordance));
console.log(JSON.stringify({coverage:cov,cnt_records:rows.length,cnt_summary:sum},null,2));
